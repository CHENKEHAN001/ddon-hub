/**
 * Build step: bake the wiki snapshot and the note map into plain JS modules.
 *
 * The exe runs as a single-executable application, so nothing may be read from
 * disk at runtime except the user's own notes. Everything the panel shows is
 * generated here from the plugin's authoritative files, which keeps this copy
 * from drifting away from the DSH panel.
 *
 * Run with: node build/bake.js
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')
const { pathToFileURL } = require('node:url')

const ROOT = path.join(__dirname, '..')
const PLUGIN = 'C:\\Users\\chenkehan\\.dsh\\plugins\\dsh-plugin-ddon-hub'

/**
 * Import one of the plugin's ESM modules from this CommonJS build script.
 *
 * `import('C:\\...')` is rejected by the ESM loader on Windows: an absolute path
 * has to go through pathToFileURL first, or it reads `C:` as the scheme.
 */
function importModule(...segments) {
  return import(pathToFileURL(path.join(PLUGIN, ...segments)).href)
}

/** Load the plugin's ESM snapshot module from CommonJS. */
async function loadSnapshot() {
  const mod = await importModule('lib', 'wiki-jobs.js')
  const data = mod.WIKI_JOBS ?? mod.default ?? mod
  if (!data || !Array.isArray(data.jobs)) throw new Error('wiki-jobs.js did not export a job tree')
  return data
}

/** The legend the DSH panel shows, kept in sync by importing the host module. */
async function loadLegend() {
  const mod = await importModule('lib', 'index.js')
  const legend = mod.internals && mod.internals.LEGEND
  if (typeof legend !== 'string' || legend === '') throw new Error('LEGEND not found in lib/index.js')
  return legend
}

/** Header banner: where the numbers came from, so nobody mistakes them for live data. */
function provenanceNote(snapshot) {
  return (
    `技能表烘入自 ${snapshot.site}（抓取于 ${snapshot.capturedAt}），不再自刷；` +
    '在线人数与新闻由本程序每次请求实时抓取。'
  )
}

function write(file, body) {
  const target = path.join(ROOT, 'src', file)
  fs.writeFileSync(target, body, 'utf8')
  console.log(`  ${file}  ${(Buffer.byteLength(body) / 1024).toFixed(0)} KB`)
}

/**
 * Tag every detail cell with the skill it belongs to.
 *
 * A note override is keyed by the wiki's own Japanese wording; a detail value has
 * no such key (the same label appears under many skills), so it is addressed by
 * job + skill + label + original value. Writing the skill name into each cell at
 * bake time keeps the request path free of markers that would otherwise leak into
 * the JSON the page receives.
 */
function tagCells(snapshot) {
  let tagged = 0
  const jobs = snapshot.jobs.map((job) => ({
    ...job,
    details: (job.details || []).map((detail) => {
      const tag = (cells) =>
        (cells || []).map((cell) => {
          tagged += 1
          return { ...cell, skill: detail.ja }
        })
      return { ...detail, cells: tag(detail.cells), attributes: tag(detail.attributes), detail: tag(detail.detail) }
    }),
  }))
  return { snapshot: { ...snapshot, jobs }, tagged }
}

/** JSON.stringify into a JS literal, keeping U+2028/29 out of the source. */
function literal(value) {
  return JSON.stringify(value).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029')
}

async function main() {
  const raw = await loadSnapshot()
  const legend = await loadLegend()
  const { snapshot, tagged } = tagCells(raw)

  const counts = {
    jobs: snapshot.jobs.length,
    details: snapshot.jobs.reduce((n, j) => n + (j.details || []).length, 0),
    rows: snapshot.jobs.reduce((n, j) => n + (j.summaryRows || []).length, 0),
    cells: tagged,
  }
  console.log('baking', counts)

  const body =
    '/**\n' +
    ' * Generated by build/bake.js — do not edit by hand.\n' +
    ` * Source: ${snapshot.source} (captured ${snapshot.capturedAt}).\n` +
    ' */\n' +
    "'use strict'\n\n" +
    `// ${provenanceNote(snapshot)}\n` +
    `const SNAPSHOT = ${literal(snapshot)}\n\n` +
    `const LEGEND = ${literal(legend)}\n\n` +
    'module.exports = { SNAPSHOT, LEGEND, PROVENANCE: ' + literal(provenanceNote(snapshot)) + ' }\n'
  write('data.js', body)

  // A tiny manifest so the build script and the UI can state what they carry.
  write(
    'manifest.js',
    '/** Generated by build/bake.js — do not edit by hand. */\n' +
      "'use strict'\n\n" +
      'module.exports = ' +
      literal({
        builtAt: new Date().toISOString(),
        capturedAt: snapshot.capturedAt,
        source: snapshot.source,
        counts,
      }) +
      '\n',
  )
  console.log('done')
}

main().catch((error) => {
  console.error('bake failed:', error && error.message ? error.message : error)
  process.exit(1)
})
