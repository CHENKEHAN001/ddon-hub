/**
 * Build step: inline the icon files as a JS module.
 *
 * The exe is one file and esbuild bundles JavaScript only, so a PNG sitting in
 * `src/assets/` does not exist at runtime. Reading it from disk therefore produced
 * a page with no favicon and no crest, silently, because the read was wrapped in a
 * try/catch. Emitting the bytes as a module removes the runtime file dependency.
 *
 * Run with: node build/make-assets.js
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')

const ROOT = path.join(__dirname, '..')
const ASSETS = path.join(ROOT, 'src', 'assets')
const OUT = path.join(ROOT, 'src', 'assets-inline.js')

/**
 * Inlined assets.
 *
 * `favicon` goes into the page head as a data URI. `faviconIco` is served at
 * `/favicon.ico` — Chrome's `--app=` window asks the site root for that exact
 * path to draw the window and taskbar icon, and a `<link rel="icon">` alone does
 * not always satisfy it. That is why the first build showed an unchanged icon in
 * the launched window while the file itself carried the right icon.
 */
const FILES = {
  favicon: 'app-256.png',
  crest: 'app-256.png',
  faviconIco: 'app.ico',
}

/** MIME type per source file, for the served copies. */
const TYPES = {
  'app-256.png': 'image/png',
  'app-512.png': 'image/png',
  'app.ico': 'image/x-icon',
}

function main() {
  const parts = []
  for (const [key, file] of Object.entries(FILES)) {
    const full = path.join(ASSETS, file)
    if (!fs.existsSync(full)) throw new Error(`missing ${file} — run: python build/make-icon.py`)
    const base64 = fs.readFileSync(full).toString('base64')
    parts.push({ key, file, base64, bytes: Buffer.byteLength(base64, 'base64'), type: TYPES[file] || 'application/octet-stream' })
  }

  const body =
    '/**\n' +
    ' * Generated by build/make-assets.js — do not edit by hand.\n' +
    ' * Icon bytes inlined so the single-file exe needs no asset files on disk.\n' +
    ' */\n' +
    "'use strict'\n\n" +
    'module.exports = {\n' +
    parts
      .map(
        (part) =>
          `  // ${part.file}, ${(part.bytes / 1024).toFixed(1)} KB, served as ${part.type}\n` +
          `  ${part.key}: 'data:${part.type};base64,${part.base64}',`,
      )
      .join('\n') +
    '\n}\n'

  fs.writeFileSync(OUT, body, 'utf8')
  console.log(`  assets-inline.js  ${(Buffer.byteLength(body) / 1024).toFixed(0)} KB`)
  for (const part of parts) console.log(`    ${part.key} <- ${part.file} (${(part.bytes / 1024).toFixed(1)} KB, ${part.type})`)

  /* Prove the module yields usable data URIs before anything bundles it. */
  delete require.cache[require.resolve(OUT)]
  const loaded = require(OUT)
  for (const part of parts) {
    const value = loaded[part.key]
    if (typeof value !== 'string' || !value.startsWith('data:')) throw new Error(`${part.key} is not a data URI`)
    const meta = /^data:([^;]+);base64,(.*)$/s.exec(value)
    if (meta === null) throw new Error(`${part.key} is not a base64 data URI`)
    if (meta[1] !== part.type) throw new Error(`${part.key} has type ${meta[1]}, expected ${part.type}`)
    const decoded = Buffer.from(meta[2], 'base64')
    if (part.file.endsWith('.png') && decoded.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') {
      throw new Error(`${part.key} is not a PNG`)
    }
    if (part.file.endsWith('.ico') && decoded.readUInt16LE(0) !== 0 || part.file.endsWith('.ico') && decoded.readUInt16LE(2) !== 1) {
      throw new Error(`${part.key} is not an ICO`)
    }
  }
  console.log('  verified: ' + parts.map((p) => p.key).join(', ') + ' decode correctly')
}

try {
  main()
} catch (error) {
  console.error('make-assets failed:', error && error.message ? error.message : error)
  process.exit(1)
}
