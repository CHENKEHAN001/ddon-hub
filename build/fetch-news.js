/**
 * 构建步骤：抓一次官方公告，烘进页面。
 *
 * 电脑版与 DSH 插件在服务端抓公告（live.ddon.org / legacyddon.com 的首页，取带日期的
 * 条目），网站版原本只有入口链接，公告区块是空的——这是四个形态之间最后的结构差异。
 *
 * 为什么烘入而不是运行时抓：
 *   - 公告一个月才更几次，烘入足够，而且页面不依赖额外请求；
 *   - 避免把抓取逻辑搬进 Worker（解析函数在 parsers.js 里，与插件逐字比对保持一致，
 *     搬第二份就会漂移）。
 *
 * 代价是公告陈旧到下次重新构建为止，所以每条都带上抓取时间，页面上也写明。
 *
 * Run with: node build/fetch-news.js
 */
'use strict'

const fs = require('node:fs')
const https = require('node:https')
const path = require('node:path')

const { parseNews } = require(path.join(__dirname, '..', 'src', 'parsers.js'))

const OUT = path.join(__dirname, '..', 'src', 'news.js')

/** 与电脑版相同的两个来源；排序与去重由 parseNews 负责。 */
const SOURCES = [
  { id: 'revival', label: 'DDON Revival', url: 'https://live.ddon.org/' },
  { id: 'legacy', label: 'LegacyDDON', url: 'https://legacyddon.com/' },
]

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
  '(KHTML, like Gecko) Chrome/152.0.0.0 Safari/537.36'

function getText(url, timeoutMs) {
  return new Promise((resolve) => {
    const request = https.get(
      url,
      { headers: { 'user-agent': UA, accept: 'text/html,application/xhtml+xml' } },
      (response) => {
        if (response.statusCode >= 300 && response.statusCode < 400 && response.headers.location) {
          response.resume()
          getText(new URL(response.headers.location, url).href, timeoutMs).then(resolve)
          return
        }
        const chunks = []
        response.on('data', (c) => chunks.push(c))
        response.on('end', () => resolve({ ok: response.statusCode === 200, status: response.statusCode, text: Buffer.concat(chunks).toString('utf8') }))
      },
    )
    request.setTimeout(timeoutMs, () => request.destroy(new Error('timeout')))
    request.on('error', (e) => resolve({ ok: false, status: 0, text: '', error: e.message }))
  })
}

async function main() {
  const results = await Promise.all(
    SOURCES.map(async (source) => {
      const response = await getText(source.url, 20000)
      if (!response.ok) return { source, entries: [], error: response.error || `HTTP ${response.status}` }
      return { source, entries: parseNews(response.text, source.url, source), error: null }
    }),
  )

  const entries = []
  for (const row of results) for (const entry of row.entries) entries.push(entry)
  entries.sort((a, b) => String(b.date).localeCompare(String(a.date)))

  const errors = results.filter((r) => r.error !== null).map((r) => `${r.source.label}: ${r.error}`)
  const fetchedAt = new Date().toISOString()

  const body =
    '/**\n' +
    ' * Generated by build/fetch-news.js — do not edit by hand.\n' +
    ` * 官方公告快照，抓取于 ${fetchedAt}\n` +
    ' */\n' +
    "'use strict'\n\n" +
    `module.exports = ${JSON.stringify({ fetchedAt, entries: entries.slice(0, 12), errors }, null, 2)}\n`
  fs.writeFileSync(OUT, body, 'utf8')

  console.log(`  news.js  ${(Buffer.byteLength(body) / 1024).toFixed(1)} KB`)
  console.log('  抓取时间:', fetchedAt)
  console.log('  公告条数:', entries.length, errors.length > 0 ? `（未取到：${errors.join('；')}）` : '')
  for (const entry of entries.slice(0, 5)) {
    console.log(`    ${entry.date}  ${entry.sourceLabel}  ${String(entry.title).slice(0, 46)}`)
  }
  if (entries.length === 0) {
    console.log('\n  注意：一条都没抓到。页面会显示"未取到"，这是可接受的降级，')
    console.log('        但请确认不是对方站点改版导致解析失效。')
  }
}

main().catch((error) => {
  console.error('fetch-news failed:', error && error.stack ? error.stack : error)
  process.exit(1)
})
