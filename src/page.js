/** Escape for text and attribute positions. */
function esc(value) {
  return String(value === null || value === undefined ? '' : value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}

/** True when a string still carries Japanese kana; U+30FB is Chinese punctuation too. */
const KANA = /[\u3040-\u30fa\u30fc-\u30ff]/

function hasKana(value) {
  return KANA.test(String(value === undefined || value === null ? '' : value))
}

/**
 * The Chinese a detail cell should show.
 *
 * Mirrors the DSH panel: the translation lives in `zhValue`, and the wiki's own
 * wording in `value` is never rendered as if it were Chinese. A missing
 * translation yields an empty string and the caller draws the 待译 marker.
 */
function cellText(cell) {
  const zh = (cell && cell.zhValue) || ''
  return zh !== '' && !hasKana(zh) ? zh : ''
}

function cellSource(cell) {
  if (!cell) return ''
  const raw = cell.value === '-' ? '—' : cell.value
  return raw === undefined || raw === null ? '' : String(raw)
}

/** The 备注 text to render: the Chinese only, never the Japanese original. */
function noteText(row) {
  const zh = (row && row.zhNote) || ''
  return hasKana(zh) ? '' : zh
}

