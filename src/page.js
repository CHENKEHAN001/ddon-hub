  /** Inline editor shared by the 备注 column and the detail values. */
  function editInline(host, current, onSave){
    var input = document.createElement('input')
    input.value = current
    input.style.width = '100%'
    host.innerHTML = ''
    host.appendChild(input)
    input.focus()
    input.select()
    var done = false
    function finish(save){
      if (done) return
      done = true
      if (!save){ renderTable(); renderDetail(); return }
      onSave(input.value)
        .then(function(){
          toast('已保存')
          /* One round trip covers both: /api/hub carries the note stats, and the
             page markup carries the job tree with the overrides already applied.
             (No backticks in here — this whole block is inside a template literal.) */
          return Promise.all([refresh(false), reloadJobs()])
        })
        .catch(function(error){
          toast('保存失败：' + error.message, true)
          renderTable(); renderDetail()
        })
    }
    input.addEventListener('keydown', function(event){
      if (event.key === 'Enter'){ event.preventDefault(); finish(true) }
      else if (event.key === 'Escape'){ event.preventDefault(); finish(false) }
    })
    input.addEventListener('blur', function(){ finish(true) })
    input.addEventListener('click', function(event){ event.stopPropagation() })
  }

  /** Re-read the job tree from the server so an edit shows in the table too. */
