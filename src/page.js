        if (row.zh && codexFold(row.zh).indexOf(needle) >= 0) return true
        if (row.ja && row.ja.toLowerCase().indexOf(needle) >= 0) return true
        if (row.en && row.en.toLowerCase().indexOf(needle) >= 0) return true
