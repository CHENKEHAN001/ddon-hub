  function codexFold(text){
    if (!text) return ''
    var codex = codexData()
    var map = codex && codex.charMap
    if (!map) return String(text).toLowerCase()
    var out = ''
    for (var i = 0; i < text.length; i++){
      var ch = text.charAt(i)
      out += (map[ch] || ch)
    }
    return out.toLowerCase()
  }

